"""Chat orchestration: conversation lookup, engine choice (LLM or rules), confirmations, persistence."""
import logging
import uuid
from datetime import datetime

from sqlalchemy.orm import Session

from ..ai import agent, rules_engine
from ..ai.intent import classify
from ..core.config import settings
from ..ai.llm_client import LLMUnavailable, get_llm_client
from ..ai.rules_engine import NO_WORDS, YES_WORDS
from ..ai.tools import ToolContext, run_pending_action
from ..ai.chat_types import ChatResult, ChatTurn, load_state, save_state
from ..models import AvaConversation, AvaMessage
from ..utils.logger import log_debug_data
from . import appointment_service as appts
from . import business_service
from .appointment_service import AppointmentError

logger = logging.getLogger("ava.chat")


def get_conversation(db: Session, session_id: str | None) -> AvaConversation | None:
    if not session_id:
        return None
    return db.query(AvaConversation).filter(AvaConversation.session_id == session_id).first()


def _create_conversation(db: Session, channel: str) -> AvaConversation:
    # Session ids are always generated by the server (128-bit random), never chosen by the client.
    conversation = AvaConversation(session_id=str(uuid.uuid4()), lead_data="{}", status="active", channel=channel)
    db.add(conversation)
    db.flush()
    return conversation


def _norm(text: str) -> str:
    return " ".join(text.lower().strip(" .!?").split())


def _confirm_pending(db, conversation, pending, message, now) -> ChatResult | None:
    """Handles the customer's answer to a pending booking/reschedule/cancel. None = not an answer."""
    answer = _norm(message)
    state = load_state(conversation)
    if answer in NO_WORDS:
        state.pop("pending_action", None)
        save_state(conversation, state)
        return ChatResult("No problem, nothing has been changed. Is there anything else I can help with?",
                          engine="llm")
    if answer not in YES_WORDS:
        # The customer changed their mind or corrected something: let the LLM handle it.
        state.pop("pending_action", None)
        save_state(conversation, state)
        return None

    state.pop("pending_action", None)
    state.pop("llm_selected_date", None)
    save_state(conversation, state)
    ctx = ToolContext(db=db, conversation=conversation, now=now)
    try:
        reply = run_pending_action(ctx, pending)
        return ChatResult(reply, engine="llm", events=ctx.events)
    except AppointmentError as exc:
        args = pending.get("args", {})
        if exc.code in {"slot_taken", "past", "invalid_slot"} and args.get("date"):
            day = datetime.fromisoformat(args["date"]).date()
            return ChatResult(f"{exc.message} Please pick another time:", "select_time",
                              {"date": day.isoformat(), "slots": appts.available_slots(db, day, now)}, engine="llm")
        return ChatResult(f"Sorry, that did not work: {exc.message}", engine="llm")


def needs_llm(db: Session, conversation: AvaConversation, message: str, turn: ChatTurn) -> bool:
    """Hybrid routing: the fast intent model answers clear messages; the LLM gets the rest.

    LLM_MODE=always sends every message to the LLM.
    """
    if settings.llm_mode == "always":
        return True
    if turn.action == "select_time":
        return True  # finishing an LLM-led booking
    if conversation.engine == "llm":
        last = (db.query(AvaMessage).filter(AvaMessage.conversation_id == conversation.id, AvaMessage.sender == "ava")
                .order_by(AvaMessage.id.desc()).first())
        if last and last.message.rstrip().endswith("?"):
            return True  # the LLM asked a follow-up question: let it continue the thread
    intent, confidence = classify(message)
    if intent == "unknown" or confidence < settings.llm_route_confidence:
        return True
    # Long messages usually carry several details at once ("I'm Rahul, 98765..., Wednesday 10am").
    return len(message.split()) > settings.llm_route_max_words


def handle_chat(db: Session, session_id: str | None, turn: ChatTurn,
                channel: str = "web") -> tuple[ChatResult, AvaConversation]:
    """Channel-independent entry point. The web widget, and later WhatsApp and phone adapters, call this.

    A WhatsApp/voice adapter would map the customer's number to a session id it stores itself,
    call handle_chat(..., channel="whatsapp"), and send result.reply back (rendering ui_action
    data as a numbered list instead of buttons).
    """
    conversation = get_conversation(db, session_id) or _create_conversation(db, channel)
    if conversation.status == "closed":
        conversation.status = "active"
    now = business_service.local_now(business_service.get_settings(db))
    state = load_state(conversation)
    message = (turn.message or "").strip()[:2000]
    turn.message = message
    client = get_llm_client()
    llm_ready = bool(client and client.is_ready())

    display_text = message
    if turn.action == "select_date" and turn.selected_date:
        display_text = turn.selected_date.strftime("%d %b %Y")
    elif turn.action == "select_time" and turn.selected_time:
        display_text = turn.selected_time.strftime("%I:%M %p")

    result: ChatResult | None = None
    try:
        if conversation.current_step:
            # A step-by-step flow is running: finish it deterministically.
            result = rules_engine.handle(db, conversation, turn, now)

        elif state.get("pending_action") and message and not turn.action:
            result = _confirm_pending(db, conversation, state["pending_action"], message, now)

        elif turn.action == "select_date" and turn.selected_date and llm_ready:
            slots = appts.available_slots(db, turn.selected_date, now)
            state["llm_selected_date"] = turn.selected_date.isoformat()
            save_state(conversation, state)
            if any(s["available"] for s in slots):
                result = ChatResult(f"Here are the free times on {turn.selected_date.strftime('%A, %d %b %Y')}:",
                                    "select_time", {"date": turn.selected_date.isoformat(), "slots": slots},
                                    engine="llm")
            else:
                result = ChatResult("Sorry, there are no free times on that date. Please pick another date:",
                                    "select_date", {"dates": appts.available_dates(db, now)}, engine="llm")

        elif turn.action == "select_time" and turn.selected_date and turn.selected_time and llm_ready:
            message = (f"I would like the appointment on {turn.selected_date.isoformat()} at "
                       f"{turn.selected_time.strftime('%H:%M')}.")

        if result is None and llm_ready and (message or turn.action) and needs_llm(db, conversation, message, turn):
            try:
                result = agent.run(db, client, conversation, message, now)
            except LLMUnavailable as exc:
                logger.warning("LLM unavailable, using rule-based engine: %s", exc)

        if result is None:
            if turn.action == "select_time" and not conversation.current_step:
                turn = ChatTurn(message=message)
            result = rules_engine.handle(db, conversation, turn, now)

        if display_text:
            db.add(AvaMessage(conversation_id=conversation.id, sender="user", message=display_text))
        db.add(AvaMessage(conversation_id=conversation.id, sender="ava", message=result.reply))
        conversation.engine = result.engine
        db.commit()
    except Exception:
        db.rollback()
        raise

    log_debug_data("Chat turn", {
        "conversation_id": conversation.id, "engine": result.engine, "step": conversation.current_step,
        "ui_action": result.ui_action, "events": result.events,
    })
    return result, conversation
