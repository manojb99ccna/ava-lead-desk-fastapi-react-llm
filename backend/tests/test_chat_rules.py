def _book(client):
    res = client.post("/api/appointments", json={"name": "Anita Rao", "phone": "9876500000", "service": "Website Design",
                                                 "appointment_date": TUESDAY.isoformat(), "start_time": "15:00"})
    return res.json()["appointment"]["booking_code"]


def test_cancel_flow_requires_code_and_phone(client, db):
    code = _book(client)
    sid = say(client, "I need to cancel my appointment")["session_id"]
    assert "booking code" in say(client, "not a code", sid)["reply"]
    say(client, code.lower(), sid)
    assert "could not find" in say(client, "9999999999", sid)["reply"]  # wrong phone resets the flow

    sid = say(client, "please cancel my booking")["session_id"]
    say(client, code, sid)
    assert "Do you want to cancel" in say(client, "9876500000", sid)["reply"]
    assert "cancelled" in say(client, "yes", sid)["reply"]
    assert db.query(AvaAppointment).one().status == "cancelled"


def test_reschedule_flow(client, db):
    code = _book(client)
    sid = say(client, "I want to reschedule")["session_id"]
    say(client, code, sid)
    r = say(client, "9876500000", sid)
    assert r["ui_action"] == "select_date"
    say(client, "", sid, action="select_date", selected_date=TUESDAY.isoformat())
    say(client, "", sid, action="select_time", selected_date=TUESDAY.isoformat(), selected_time="16:00")
    assert "moved" in say(client, "yes", sid)["reply"]
    assert db.query(AvaAppointment).one().appointment_date.hour == 16


