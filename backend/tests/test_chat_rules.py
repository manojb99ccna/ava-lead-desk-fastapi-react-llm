"""Rule-based Ava (no LLM configured)."""
from app.models import AvaAppointment, AvaConversation, AvaHandoffRequest, AvaLead, AvaMessage

from .conftest import TUESDAY


def say(client, message, session_id=None, **extra):
    res = client.post("/api/chat", json={"message": message, "session_id": session_id, **extra})
    assert res.status_code == 200, res.text
    return res.json()


def test_greeting_uses_business_name_and_server_session(client, db):
    first = say(client, "hello", session_id="client-chosen-id")
    assert "WebeXcellence" in first["reply"]
    assert first["session_id"] != "client-chosen-id"  # ids are generated by the server
    assert first["engine"] == "rules"
    again = say(client, "hi", first["session_id"])
    assert again["session_id"] == first["session_id"]
    assert db.query(AvaMessage).count() == 4


