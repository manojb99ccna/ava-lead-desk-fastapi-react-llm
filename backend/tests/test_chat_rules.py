def test_full_booking_flow_with_confirmation(client, db):
    r = say(client, "I want to book an appointment")
    sid = r["session_id"]
    assert "name" in r["reply"].lower()
    assert "valid name" in say(client, "what do you do", sid)["reply"]
    say(client, "Rahul Verma", sid)
    assert "valid phone" in say(client, "12", sid)["reply"]
    r = say(client, "9876501234", sid)
    assert "Website Design" in r["reply"]  # services are listed
    r = say(client, "Website Design", sid)
    assert r["ui_action"] == "select_date"
    r = say(client, "", sid, action="select_date", selected_date=TUESDAY.isoformat())
    assert r["ui_action"] == "select_time"
    r = say(client, "", sid, action="select_time", selected_date=TUESDAY.isoformat(), selected_time="10:00")
    assert "confirm" in r["reply"].lower()
    assert db.query(AvaAppointment).count() == 0  # nothing booked before confirmation
    r = say(client, "yes", sid)
    assert "Booking code: AVA-" in r["reply"]
    appointment = db.query(AvaAppointment).one()
    assert appointment.name == "Rahul Verma" and appointment.status == "pending"
    conversation = db.query(AvaConversation).filter_by(session_id=sid).one()
    assert conversation.current_step is None and conversation.customer_id == appointment.customer_id


def test_booking_can_be_declined(client, db):
    sid = say(client, "book a meeting")["session_id"]
